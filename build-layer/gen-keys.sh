#!/usr/bin/env bash
# Generate your own signing keys for an InkPalm KompaktOS build. Keys never enter any git tree.
#
#     build-layer/gen-keys.sh [KEYS_DIR]                     APK/platform keys + keys.mk + Android.bp
#     build-layer/gen-keys.sh --apex-from-tree TREE [KEYS_DIR]
#                                                            APEX payload keys for every apex_key in
#                                                            a synced tree (build.sh runs this itself)
#
# KEYS_DIR defaults to ~/.inkpalm-keys and must be OUTSIDE every git work tree. build.sh copies
# it into $TREE/vendor/lineage-priv/keys, the path LineageOS (and upstream KompaktOS's signing.md)
# expects; vendor/lineage/config/common.mk -includes keys.mk from there.
#
# Layout written (same as upstream KompaktOS signing.md):
#   releasekey platform shared media networkstack nfc bluetooth sdk_sandbox testkey  .{pk8,x509.pem}
#   com.android.<module>.{pem,avbpubkey}     APEX payload keys, RSA 4096 (APEX requires SHA256_RSA4096)
#   keys.mk                                  the ONLY place the certificate is set
#   Android.bp                               android_app_certificate "inkpalm-releasekey" for
#                                            PRODUCT_CERTIFICATE_OVERRIDES
#
# The key list follows upstream signing.md for lineage-23.2; LineageOS's wiki additionally lists
# "verifiedboot" (AVB of a full device build), which a system-image-only build does not use.
# Keys are unencrypted (build-time signing reads them non-interactively): protect the directory
# and keep an offline backup. Losing them means the next build with new keys needs a data wipe.
#
# Env: KEY_SUBJECT  certificate subject (default below; never use android@android.com, which the
#                   post-build check uses to spot AOSP test keys)
#      APK_KEY_BITS RSA size of the APK keys (default 2048, like AOSP's make_key)
set -euo pipefail
LOG_TAG=keys
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck source=lib/common.sh
. "$HERE/lib/common.sh"

APEX_TREE=
if [ "${1:-}" = --apex-from-tree ]; then
    APEX_TREE=${2:?usage: gen-keys.sh --apex-from-tree TREE [KEYS_DIR]}
    shift 2
fi
KEYS_DIR=${1:-$HOME/.inkpalm-keys}
SUBJECT=${KEY_SUBJECT:-/C=XX/O=InkPalm KompaktOS/OU=Release/CN=InkPalm KompaktOS release keys}
BITS=${APK_KEY_BITS:-2048}
APK_KEYS="releasekey platform shared media networkstack nfc bluetooth sdk_sandbox testkey"

need openssl
case "$SUBJECT" in *android@android.com*) die "KEY_SUBJECT must not use the AOSP test-key address";; esac

umask 077
# Refuse before creating anything: check the nearest existing ancestor.
anc=$KEYS_DIR
while [ ! -d "$anc" ]; do anc=$(dirname "$anc"); done
in_git_tree "$anc" && die "$KEYS_DIR is inside a git work tree; keys must live outside any repo"
mkdir -p "$KEYS_DIR"
KEYS_DIR=$(abs_dir "$KEYS_DIR")
chmod 0700 "$KEYS_DIR"

# make_key equivalent (AOSP development/tools/make_key): RSA key, self-signed x509 (10000 days,
# SHA-256), private key as unencrypted PKCS#8 DER .pk8.
make_key() {
    local base=$KEYS_DIR/$1 tmp
    if [ -f "$base.pk8" ] && [ -f "$base.x509.pem" ]; then
        log "keep  $1 (exists)"
        return
    fi
    tmp=$(mktemp "$KEYS_DIR/.tmp.XXXXXX")
    openssl genrsa -f4 -out "$tmp" "$BITS" 2>/dev/null
    openssl req -new -x509 -sha256 -key "$tmp" -out "$base.x509.pem" -days 10000 -subj "$SUBJECT"
    openssl pkcs8 -in "$tmp" -topk8 -outform DER -out "$base.pk8" -nocrypt
    rm -f "$tmp"
    log "made  $1 ($BITS-bit)"
}

if [ -z "$APEX_TREE" ]; then
    for k in $APK_KEYS; do make_key "$k"; done

    if [ ! -f "$KEYS_DIR/keys.mk" ]; then
        cat > "$KEYS_DIR/keys.mk" <<'EOF'
# InkPalm KompaktOS signing (generated by build-layer/gen-keys.sh). Lives in
# vendor/lineage-priv/keys/ inside the tree; vendor/lineage/config/common.mk -includes it.
# Set the certificate HERE ONLY: PRODUCT_DEFAULT_DEV_CERTIFICATE is single-valued and the
# first-inherited value wins silently. The vendor/lineage-priv/ prefix is what makes
# LineageOS report the build as release-keys (see upstream KompaktOS signing.md).
PRODUCT_DEFAULT_DEV_CERTIFICATE := vendor/lineage-priv/keys/releasekey
PRODUCT_MAINLINE_BLUETOOTH_SEPOLICY_DEV_CERTIFICATES := vendor/lineage-priv/keys

# APKs that declare their own `certificate:` module never see the default cert and ship
# signed with an AOSP in-tree key. build.sh's post-build check lists them ("AOSP test key").
# Override each one against the certificate module in Android.bp next to this file.
# Format <app module>:<certificate module>; the wrong way round is silently ignored.
# Upstream KompaktOS found ten such APKs on lineage-23.2, e.g. ServiceWifiResources.
# UNVERIFIED: the full list; fill it in from the first build's report, then rebuild.
#PRODUCT_CERTIFICATE_OVERRIDES += \
#    ServiceWifiResources:inkpalm-releasekey
EOF
        log "wrote keys.mk"
    fi
    if [ ! -f "$KEYS_DIR/Android.bp" ]; then
        cat > "$KEYS_DIR/Android.bp" <<'EOF'
// Certificate module for PRODUCT_CERTIFICATE_OVERRIDES in keys.mk (build-layer/gen-keys.sh).
android_app_certificate {
    name: "inkpalm-releasekey",
    certificate: "releasekey",
}
EOF
        log "wrote Android.bp"
    fi
    chmod 0600 "$KEYS_DIR"/*
    log "APK keys ready in $KEYS_DIR"
    log "APEX payload keys are made from a synced tree: build.sh does it before the first build"
    log "BACK UP $KEYS_DIR now (offline). It is never committed or uploaded by these scripts."
    exit 0
fi

# ---- APEX payload keys -------------------------------------------------------------------
# build/soong/apex/key.go looks for each apex_key's private_key/public_key file names in the
# default certificate directory and silently falls back to the in-tree (public!) AOSP keys
# when they are missing. So generate one pair per apex_key found in the synced source.
TREE=$(abs_dir "$APEX_TREE")
AVBTOOL=$TREE/external/avb/avbtool.py
[ -f "$AVBTOOL" ] || die "no $AVBTOOL: is $TREE a synced tree?"
need python3 find
log "scanning $TREE for apex_key modules (skips out/, .repo/, prebuilts/ and test dirs)"
LIST=$(mktemp); BPS=$(mktemp)
trap 'rm -f "$LIST" "$BPS"' EXIT
# grep/xargs exit non-zero on "no match"; that must not abort the scan.
{ find "$TREE" \( -path "$TREE/out" -o -path "$TREE/.repo" -o -path "$TREE/prebuilts" \) -prune -o \
       -name Android.bp -print 2>/dev/null |
      grep -v -E '/(tests?|testdata|testing|cts)/' |
      xargs grep -l 'apex_key' 2>/dev/null; } > "$BPS" || true
python3 -I -c '
import re, sys
seen = set()
for path in open(sys.argv[1]).read().split():
    try:
        src = open(path, errors="replace").read()
    except OSError:
        continue
    for m in re.finditer(r"\bapex_key\s*\{", src):
        depth, i = 1, m.end()
        while i < len(src) and depth:
            depth += {"{": 1, "}": -1}.get(src[i], 0)
            i += 1
        body = src[m.end():i]
        pk = re.search(r"private_key\s*:\s*\"([^\"]+)\"", body)
        pub = re.search(r"public_key\s*:\s*\"([^\"]+)\"", body)
        if not pk or not pub or pk.group(1).startswith(":") or pub.group(1).startswith(":"):
            continue
        a, b = pk.group(1).split("/")[-1], pub.group(1).split("/")[-1]
        if re.search(r"(^|[._-])test", a) or (a, b) in seen:
            continue
        seen.add((a, b))
        print(a, b)
' "$BPS" > "$LIST"
n=0; made=0
while read -r priv pub; do
    n=$((n + 1))
    if [ -f "$KEYS_DIR/$priv" ] && [ -f "$KEYS_DIR/$pub" ]; then continue; fi
    openssl genrsa -f4 -out "$KEYS_DIR/$priv" 4096 2>/dev/null
    python3 "$AVBTOOL" extract_public_key --key "$KEYS_DIR/$priv" --output "$KEYS_DIR/$pub"
    chmod 0600 "$KEYS_DIR/$priv" "$KEYS_DIR/$pub"
    made=$((made + 1))
done < "$LIST"
log "apex_key modules found: $n, new key pairs: $made (in $KEYS_DIR)"
[ "$n" -gt 0 ] || die "found no apex_key modules; the tree looks incomplete"
[ "$made" -eq 0 ] || log "new APEX keys: BACK UP $KEYS_DIR again"
